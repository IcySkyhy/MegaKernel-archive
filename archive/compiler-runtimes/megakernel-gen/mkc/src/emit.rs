fn rope_code(m: &Model) -> String {
    // inv_freq, exactly as transformers computes it -- verified against the
    // reference tables by the generated harness (tests/test_rope).
    let mut s = String::new();
    let rd = m.rope.rotary_dim;
    let _ = writeln!(s, "static void mk_inv_freq(double* inv, double* attn_factor) {{");
    let _ = writeln!(s, "    const double base = {:.9};", m.rope.theta);
    let _ = writeln!(s, "    const int dim = {};", rd);
    let _ = writeln!(s, "    *attn_factor = 1.0;");
    let _ = writeln!(s, "    for (int i = 0; i < dim/2; ++i) inv[i] = 1.0 / pow(base, (double)(2*i)/dim);");
    match &m.rope.scaling {
        RopeScaling::None => {}
        RopeScaling::Linear { factor } => {
            let _ = writeln!(s, "    for (int i = 0; i < dim/2; ++i) inv[i] /= {:.9};", factor);
        }
        RopeScaling::Llama3 {
            factor,
            low_freq_factor,
            high_freq_factor,
            original_max_position,
        } => {
            let _ = writeln!(s, "    const double f = {:.9}, lo = {:.9}, hi = {:.9}, oc = {:.1};",
                factor, low_freq_factor, high_freq_factor, *original_max_position as f64);
            let _ = writeln!(s, "    const double lw = oc/lo, hw = oc/hi;");
            let _ = writeln!(s, "    for (int i = 0; i < dim/2; ++i) {{");
            let _ = writeln!(s, "        const double wl = 2.0*M_PI/inv[i];");
            let _ = writeln!(s, "        double v = (wl > lw) ? inv[i]/f : inv[i];");
            let _ = writeln!(s, "        if (!(wl < hw) && !(wl > lw)) {{");
            let _ = writeln!(s, "            const double sm = (oc/wl - lo)/(hi - lo);");
            let _ = writeln!(s, "            v = (1.0-sm)*v/f + sm*v;");
            let _ = writeln!(s, "        }}");
            let _ = writeln!(s, "        inv[i] = v;");
            let _ = writeln!(s, "    }}");
        }
        RopeScaling::Yarn {
            factor,
            beta_fast,
            beta_slow,
            original_max_position,
            attn_factor,
            truncate,
        } => {
            let af = if *attn_factor > 0.0 && (*attn_factor - 1.0).abs() > 1e-9 {
                *attn_factor as f64
            } else {
                0.0
            };
            let _ = writeln!(s, "    const double f = {:.9}, bf = {:.9}, bs = {:.9}, om = {:.1};",
                factor, beta_fast, beta_slow, *original_max_position as f64);
            let _ = writeln!(s, "    *attn_factor = {};",
                if af > 0.0 { format!("{:.9}", af) } else { "(f <= 1.0 ? 1.0 : 0.1*log(f) + 1.0)".into() });
            let _ = writeln!(s, "    double lowd = (dim*log(om/(bf*2.0*M_PI)))/(2.0*log(base));");
            let _ = writeln!(s, "    double highd = (dim*log(om/(bs*2.0*M_PI)))/(2.0*log(base));");
            if *truncate {
                let _ = writeln!(s, "    lowd = floor(lowd); highd = ceil(highd);");
            }
            let _ = writeln!(s, "    double lo = fmax(lowd, 0.0), hi = fmin(highd, (double)dim-1.0);");
            let _ = writeln!(s, "    if (lo == hi) hi += 0.001;");
            let _ = writeln!(s, "    for (int i = 0; i < dim/2; ++i) {{");
            let _ = writeln!(s, "        const double pf = pow(base, (double)(2*i)/dim);");
            let _ = writeln!(s, "        const double ex = 1.0/pf, in = 1.0/(f*pf);");
            let _ = writeln!(s, "        double ramp = ((double)i - lo)/(hi - lo);");
            let _ = writeln!(s, "        ramp = fmin(fmax(ramp, 0.0), 1.0);");
            let _ = writeln!(s, "        const double exf = 1.0 - ramp;");
            let _ = writeln!(s, "        inv[i] = in*(1.0-exf) + ex*exf;");
            let _ = writeln!(s, "    }}");
        }
    }
    let _ = writeln!(s, "}}");
    s
}

