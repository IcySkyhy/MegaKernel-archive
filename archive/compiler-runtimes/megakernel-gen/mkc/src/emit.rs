/// A standalone decode-timing driver, so `mkc build --verify` can rank
/// candidates without Python and without reading the checkpoint.
fn mkbench_cpp() -> String {
    r##"// generated by mkc -- decode timing on synthetic weights
#include "mk_api.h"
#include <cstdio>
#include <cstdlib>
#include <vector>
int main(int argc, char** argv) {
    const int ctx    = argc > 1 ? atoi(argv[1]) : 1024;
    const int steps  = argc > 2 ? atoi(argv[2]) : 64;
    const int device = argc > 3 ? atoi(argv[3]) : 0;
    MkCtx* c = mk_create_fake(0, ctx + steps + 8, device);
    if (!c) { fprintf(stderr, "create failed\n"); return 1; }
    std::vector<int> ids(ctx + steps + 1);
    for (size_t i = 0; i < ids.size(); ++i) ids[i] = (int)((i * 2654435761u) % (unsigned)mk_vocab(c));
    mk_reset(c);
    if (mk_set_tokens(c, ids.data(), (int)ids.size()) != 0) return 1;
    if (mk_run(c, ctx, 0) != 0) return 1;                 // prefill
    // N-vs-1 differencing cancels the first step's cold caches, and the best of
    // three cancels a neighbour: a single sample here has picked the wrong
    // schedule before.
    double best = 1e30;
    for (int rep = 0; rep < 3; ++rep) {
        mk_set_pos(c, ctx); if (mk_run(c, 1, 0) != 0) return 1;
        const double t1 = mk_last_ms(c);
        mk_set_pos(c, ctx); if (mk_run(c, steps, 0) != 0) return 1;
        const double tN = mk_last_ms(c);
        const double per = (tN - t1) / (steps - 1);
        if (per > 0 && per < best) best = per;
    }
    printf("%.6f\n", best);                               // ms per decode token
    mk_free(c);
    return 0;
}
"##
    .to_string()
}

fn makefile(_m: &Model, arch: &str, inc: &str) -> String {
    format!(r#"# generated by mkc
# NB: the variable is MKARCH, not ARCH -- the module environments on HPC systems
# export ARCH=x86_64, which nvcc then rejects.
NVCC    ?= nvcc
MKARCH  ?= {arch}
MKINC   ?= {inc}
# --use_fast_math is deliberately OFF: it degrades expf/rsqrtf enough to move
# logits, and buys nothing on a kernel that is memory bound.
# -cudart shared: the .so is dlopen'd next to PyTorch, which has its own
# CUDA runtime; two static runtimes in one process is asking for trouble.
CFLAGS  = -O3 -std=c++17 -arch=$(MKARCH) -I$(MKINC) -I. -lineinfo -Xcompiler -fPIC -cudart shared
CFLAGS += -Xptxas -v

# The runtime headers are prerequisites.  Leaving them out is the classic way to
# "validate" a kernel rewrite that was never compiled: the object is stale and
# the .so silently keeps the old code.
MKHDRS  = $(wildcard $(MKINC)/mk/*.cuh)

all: libmk.so

libmk.so: megakernel.o stages.o runtime.o
	$(NVCC) $(CFLAGS) -shared -o $@ $^

megakernel.o: megakernel.cu stages.cuh kernel.h model.h $(MKHDRS)
	$(NVCC) $(CFLAGS) -c -o $@ $< 2> ptxas.log; cat ptxas.log

stages.o: stages.cu stages.cuh kernel.h model.h $(MKHDRS)
	$(NVCC) $(CFLAGS) -c -o $@ $<

runtime.o: runtime.cu kernel.h model.h weights.h mk_api.h $(MKHDRS)
	$(NVCC) $(CFLAGS) -c -o $@ $<

mkbench: mkbench.cpp libmk.so
	$(NVCC) -O2 -std=c++17 -I. -o $@ mkbench.cpp -L. -lmk -Xlinker -rpath -Xlinker $(CURDIR)

clean:
	rm -f *.o *.so ptxas.log mkbench
.PHONY: all clean
"#, arch = arch, inc = inc)
}

pub fn emit_all(m: &Model, p: &Plan, hw: &Hw, out: &Path, ctx: usize) -> Result<(), String> {
    fs::create_dir_all(out).map_err(|e| format!("{}: {}", out.display(), e))?;
    let g = Gen { m, p, hw, ctx };
    let (ws, arena) = layout(m);

    // Write only what changed.  `mkc build` re-emits the tree once per candidate
    // schedule, and most of the tree is the same every time; leaving mtimes
    // alone is what lets make rebuild the one translation unit that moved
    // instead of all of them.
    let w = |name: &str, body: String| -> Result<(), String> {
        let path = out.join(name);
        if fs::read_to_string(&path).map(|old| old == body).unwrap_or(false) {
            return Ok(());
        }
        fs::write(&path, body).map_err(|e| format!("{}: {}", name, e))
    };
    w("model.h", g.model_h())?;
    w("kernel.h", g.kernel_h())?;
    w("stages.cuh", g.stages_cuh())?;
    w("megakernel.cu", g.megakernel_cu())?;
    w("stages.cu", g.stages_cu())?;
    w("weights.h", weights_h(m, &ws, arena))?;
    w("runtime.cu", runtime_cu(m, p, &ws))?;
    w("mk_api.h", mk_api_h())?;
    let arch = format!("sm_{}{}", hw.sm_arch / 10, if hw.sm_arch == 90 { "0a".to_string() } else { format!("{}", hw.sm_arch % 10) });
    let inc = std::env::var("MKGEN_ROOT")
        .map(|r| format!("{}/runtime/include", r))
        .unwrap_or_else(|_| "../../runtime/include".into());
    w("mkbench.cpp", mkbench_cpp())?;
    w("Makefile", makefile(m, &arch, &inc))?;

    // machine-readable description of what was compiled, for the harness and
    // for the report; also the record that makes a build reproducible: the
    // model, the schedule, the machine model it was priced against and when
    // that was measured.
    let mut b = String::new();
    let _ = writeln!(b, "{{");
    let _ = writeln!(b, "  \"name\": \"{}\",", m.name);
    let _ = writeln!(b, "  \"arch\": \"{}\",", m.arch);
    let _ = writeln!(b, "  \"mkc_version\": \"{}\",", crate::VERSION);
    let _ = writeln!(b, "  \"device\": \"{}\",", hw.device);
    // which machine model this was compiled against: a number produced on one
    // node's calibration is not comparable with one produced on another's, and
    // this is where you find out
    let _ = writeln!(b, "  \"hw_calibrated_at\": \"{}\", \"hw_schema\": {},",
                     hw.calibrated_at, hw.schema);
    let _ = writeln!(b, "  \"hidden\": {}, \"layers\": {}, \"vocab\": {},", m.hidden, m.n_layers, m.vocab);
    let _ = writeln!(b, "  \"n_heads\": {}, \"n_kv_heads\": {}, \"head_dim\": {},", m.attn.n_heads, m.attn.n_kv_heads, m.attn.head_dim);
    let _ = writeln!(b, "  \"act_dtype\": \"{}\", \"q_ffn\": \"{}\",", m.act_dtype, m.q_ffn.tag());
    let _ = writeln!(b, "  \"moe\": {},", m.is_moe());
    // the same expression codegen emits as M::MAXCTX; the two used to disagree
    let _ = writeln!(b, "  \"ctx\": {}, \"max_ctx\": {},",
                     ctx, (ctx + (ctx / 2).max(512)).next_power_of_two().max(1024));
    let _ = writeln!(b, "  \"nt\": {}, \"grid_planned\": {}, \"attn_splits\": {},", p.nt, p.blocks, p.attn_splits);
    let _ = writeln!(b, "  \"arena_bytes\": {},", arena);
    let _ = writeln!(b, "  \"barriers_per_token\": {},", p.barriers_per_token);
    let _ = write!(b, "  \"stages\": [");
    for (i, st) in p.layer.iter().filter(|x| x.barrier_after).enumerate() {
        let _ = write!(b, "{}\"{}\"", if i > 0 { ", " } else { "" }, st.kind.short());
    }
    let _ = writeln!(b, "],");
    let _ = write!(b, "  \"stage_pred_us\": [");
    for (i, st) in p.layer.iter().filter(|x| x.barrier_after).enumerate() {
        let _ = write!(b, "{}{:.3}", if i > 0 { ", " } else { "" }, st.est_us);
    }
    let _ = writeln!(b, "],");
    let _ = write!(b, "  \"stage_bytes\": [");
    for (i, st) in p.layer.iter().filter(|x| x.barrier_after).enumerate() {
        let _ = write!(b, "{}{}", if i > 0 { ", " } else { "" }, st.bytes);
    }
    let _ = writeln!(b, "],");
    let _ = writeln!(b, "  \"lm_head_pred_us\": {:.3},", p.tail.iter().map(|s| s.est_us).sum::<f64>());
    let _ = writeln!(b, "  \"lm_head_bytes\": {},", p.tail.iter().map(|s| s.bytes).sum::<u64>());
    let _ = writeln!(b, "  \"predicted_ms\": {:.4},", p.est_ms);
    let rl = crate::report::roofline(m, ctx);
    let _ = writeln!(b, "  \"bytes_per_token\": {},", rl.total);
    let _ = writeln!(b, "  \"roofline_ms\": {:.4},", rl.ms_at(hw.stream_peak_gbs));
    // the same bytes charged at each format's own measured gemv ceiling
    let _ = writeln!(b, "  \"floor_ms\": {:.4},", rl.floor_ms(hw));
    let _ = writeln!(b, "  \"stream_peak_gbs\": {}", hw.stream_peak_gbs);
    let _ = writeln!(b, "}}");
    w("build.json", b)?;

    let mut txt = String::new();
    let _ = writeln!(txt, "{}", rl.render(hw.stream_peak_gbs));
    let _ = writeln!(txt, "{}", p.render(hw));
    w("plan.txt", txt)?;
    Ok(())
}
